CREATE VIEW veterinary.v_ingestion_eligible AS
SELECT n.id AS source_record_id,n.source_event_id,n.clinic_id,n.disease_code,n.species_code,
       n.sex_code,n.castration_code,n.age_band_code,n.breed_name,n.is_mixed_breed,
       n.notification_date,n.territory_basis,n.municipality_ibge,n.neighborhood_id,
       n.validated_at
FROM veterinary.notifications n
WHERE n.status='VALIDATED'
AND NOT EXISTS(
 SELECT 1 FROM veterinary.notifications v
 WHERE v.supersedes_notification_id=n.id AND v.status='VALIDATED'
)
AND NOT EXISTS(
 SELECT 1 FROM veterinary.notification_events e
 WHERE e.notification_id=n.id AND e.event_type='CANCEL'
);

