#!/usr/bin/env bash
set -Eeuo pipefail

registry="${NSS_LOCAL_REGISTRY:-127.0.0.1:5000}"
namespace="${NSS_LOCAL_IMAGE_NAMESPACE:-nss}"
release_tag="${NSS_RELEASE_TAG:-$(date -u +%Y%m%d%H%M%S)}"
output_file="${NSS_IMAGE_DIGEST_FILE:-${PWD}/.nss-image-digests.env}"

die() { printf 'ERRO: %s\n' "$*" >&2; exit 1; }

command -v docker >/dev/null || die 'docker não encontrado'
docker info >/dev/null 2>&1 || die 'Docker daemon indisponível'
docker version >/dev/null 2>&1 || die 'Docker indisponível'

declare -A source_images=(
  [database]="${NSS_DATABASE_BUILD_IMAGE:-nss-database:0001}"
  [java]="${NSS_JAVA_BUILD_IMAGE:-nss-java:local}"
  [frontend]="${NSS_FRONTEND_BUILD_IMAGE:-nss-frontend:local}"
  [pipeline]="${NSS_PIPELINE_BUILD_IMAGE:-nss-pipeline:local}"
)

tmp_file=$(mktemp "${output_file}.XXXXXX")
trap 'rm -f "$tmp_file"' EXIT
umask 077
{
  printf '# Generated by scripts/publish-local-images.sh; release=%s\n' "$release_tag"
  printf 'NSS_PIPELINE_IMAGE_MODE=digest\n'
} >"$tmp_file"

for component in database java frontend pipeline; do
  source_image="${source_images[$component]}"
  target_image="${registry}/${namespace}/nss-${component}:${release_tag}"
  docker image inspect "$source_image" >/dev/null 2>&1 ||
    die "imagem local ausente: ${source_image}"
  printf 'Publicando %s -> %s\n' "$source_image" "$target_image"
  docker tag "$source_image" "$target_image"
  docker push "$target_image"
  digest_reference=$(docker image inspect "$target_image" --format '{{index .RepoDigests 0}}')
  [[ "$digest_reference" =~ ^${registry//./\.}/${namespace//./\.}/nss-${component}@sha256:[[:xdigit:]]{64}$ ]] ||
    die "registry não retornou RepoDigest OCI válido para ${component}: ${digest_reference}"
  variable_name="NSS_${component^^}_IMAGE"
  printf '%s=%s\n' "$variable_name" "$digest_reference" >>"$tmp_file"
done

mkdir -p "$(dirname "$output_file")"
mv -f "$tmp_file" "$output_file"
trap - EXIT
chmod 600 "$output_file"
printf 'Release digest gerada em %s\n' "$output_file"
